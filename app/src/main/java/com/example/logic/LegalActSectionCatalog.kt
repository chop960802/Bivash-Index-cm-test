  fun sectionsForAct(actType: LegalActType): List<LegalSectionItem> =
    when (actType) {
      LegalActType.BNS -> bnsSections
      LegalActType.POCSO -> pocsoSections
      LegalActType.OTHERS -> emptyList()
    }

  fun searchSections(actType: LegalActType, query: String): List<LegalSectionItem> {
    val all = sectionsForAct(actType)
    val needle = query.trim()
    if (needle.isEmpty()) return all
    val cleanNum = needle.removePrefix("sec").removePrefix("Sec").removePrefix("section").trim()
    val exactMatches = all.filter { it.sectionNumber.equals(cleanNum, ignoreCase = true) }
    val numPrefixMatches =
      all.filter {
        !it.sectionNumber.equals(cleanNum, ignoreCase = true) &&
          it.sectionNumber.startsWith(cleanNum, ignoreCase = true)
      }
    val textMatches =
      all.filter {
        !it.sectionNumber.startsWith(cleanNum, ignoreCase = true) &&
          (it.sectionNumber.contains(needle, ignoreCase = true) ||
            it.shortTitle.contains(needle, ignoreCase = true))
      }
    return exactMatches + numPrefixMatches + textMatches
  }
